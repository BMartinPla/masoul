export type RoomRole = 'start' | 'combat' | 'shrine' | 'scroll' | 'merchant' | 'boss' | 'exit';

export interface RoomTemplate {
  id: string;
  role: RoomRole;
  rows: readonly string[]; // Each row has fixed uniform width; height = 22 tiles (352px)
}

/**
 * Tile legend:
 * '#' = Solid gothic stone
 * '=' = One-way wooden rafter platform
 * '^' = Iron floor spikes
 * '.' = Open air
 * 'T' = Wall torch
 * 'B' = Floor brazier
 * 'W' = Stained-glass rose window
 * 'N' = Hanging banner
 * 'C' = Hanging chain
 * 'G' = Vanguard / heavy melee enemy spawn (wide floor / bridge)
 * 'V' = Vantage marksman / caster enemy spawn (elevated sniper balcony)
 * 'E' = Terrain-smart ground enemy spawn
 * 'F' = Flying / vault enemy spawn
 * 'U' = Ravenous Mimic spawn
 * 'L' = Ornate chest
 * 'P' = Breakable barrel/crate
 * 'S' = Player start spawn
 * 'R' = Relic Shrine
 * 'K' = Trinity Scroll Pedestal
 * 'A' = Blood Shrine
 * 'O' = Waystone Obelisk
 * 'I' = Lore Tablet
 * 'M' = Merchant Stand
 * 'X' = Primary Biome Exit Portal
 * 'Y' = Alternate Branching Biome Exit Portal (only spawned if biome.altNextBiome exists)
 * 'Z' = Boss Spawn
 *
 * INVARIANT: Every template is 22 rows tall (indices 0..21).
 * Standard connecting doorway floor is at row 18 (solid '#' at rows 18..21),
 * with open air '.' at rows 12..17 on BOTH left and right outer columns so
 * any two stitched templates connect seamlessly!
 * Architectural tiers follow a strict 3-tile jump cadence:
 * Row 18 (floor) -> Row 15 (Tier 1) -> Row 12 (Tier 2) -> Row 9 (Tier 3) -> Row 6 (Tier 4).
 */
