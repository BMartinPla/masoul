# Tuple: (y_offset_px_from_baseline, rows_top_to_bottom)
GlyphDef = Tuple[int, List[str]]


def normalize_glyph(y_offset: int, rows: List[str]) -> Tuple[int, int, List[str]]:
    width = max((len(r) for r in rows), default=1)
    padded = [r.ljust(width, ".") for r in rows]
    return width, y_offset, padded


