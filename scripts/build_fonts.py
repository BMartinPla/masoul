def draw_pixel_rect(pen: TTGlyphPen, x0: int, y0: int, x1: int, y1: int) -> None:
    """Clockwise outer contour in TrueType coordinates."""
    pen.moveTo((x0, y0))
    pen.lineTo((x0, y1))
    pen.lineTo((x1, y1))
    pen.lineTo((x1, y0))
    pen.closePath()


def build_font(
    family_name: str,
    raw_glyphs: Dict[str, GlyphDef],
    cap_height: int,
    x_height: int,
    space_px: int,
) -> None:
    unit_px = 100
    units_per_em = 1000
    ascent = cap_height * unit_px
    descent = -2 * unit_px

    normalized = {ch: normalize_glyph(y_off, rows) for ch, (y_off, rows) in raw_glyphs.items()}

    glyph_names = [".notdef", "space"]
    cmap: Dict[int, str] = {32: "space", 160: "space"}
    char_to_gname: Dict[str, str] = {}

    for ch in normalized:
        cp = ord(ch)
        gname = f"uni{cp:04X}"
        glyph_names.append(gname)
        cmap[cp] = gname
        char_to_gname[ch] = gname

    fb = FontBuilder(units_per_em, isTTF=True)
    fb.setupGlyphOrder(glyph_names)
    fb.setupCharacterMap(cmap)

    glyf_map = {}
    metrics = {}

    # .notdef box
    pen_nd = TTGlyphPen(None)
    draw_pixel_rect(pen_nd, 0, 0, 500, cap_height * unit_px)
    glyf_map[".notdef"] = pen_nd.glyph()
    metrics[".notdef"] = (600, 0)

    # space
    pen_sp = TTGlyphPen(None)
    glyf_map["space"] = pen_sp.glyph()
    metrics["space"] = (space_px * unit_px, 0)

    for ch, (w_px, y_off, rows) in normalized.items():
        gname = char_to_gname[ch]
        pen = TTGlyphPen(None)
        h_px = len(rows)
        has_pixels = False

        for r_idx, row_str in enumerate(rows):
            y0 = (y_off + (h_px - 1 - r_idx)) * unit_px
            y1 = y0 + unit_px
            c = 0
            while c < len(row_str):
                if row_str[c] == "#":
                    start_c = c
                    while c < len(row_str) and row_str[c] == "#":
                        c += 1
                    draw_pixel_rect(pen, start_c * unit_px, y0, c * unit_px, y1)
                    has_pixels = True
                else:
                    c += 1

        glyf_map[gname] = pen.glyph() if has_pixels else TTGlyphPen(None).glyph()
        metrics[gname] = ((w_px + 1) * unit_px, 0)

    fb.setupGlyf(glyf_map)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ascent, descent=descent, lineGap=200)
    fb.setupNameTable({
        "familyName": family_name,
        "styleName": "Regular",
        "uniqueFontIdentifier": f"{family_name}-Regular-1.0",
        "fullName": family_name,
        "psName": f"{family_name}-Regular",
        "version": "Version 1.0",
    })
    fb.setupOS2(
        sTypoAscender=ascent,
        sTypoDescender=descent,
        sTypoLineGap=200,
        usWinAscent=ascent + 100,
        usWinDescent=abs(descent) + 100,
        sxHeight=x_height * unit_px,
        sCapHeight=cap_height * unit_px,
    )
    fb.setupPost()

    OUT_FONTS.mkdir(parents=True, exist_ok=True)
    ttf_path = OUT_FONTS / f"{family_name}.ttf"
    woff_path = OUT_FONTS / f"{family_name}.woff"

    fb.font.flavor = None
    fb.save(str(ttf_path))

    fb.font.flavor = "woff"
    fb.save(str(woff_path))

    # Reload and verify both files
    for p in (ttf_path, woff_path):
        check = TTFont(str(p))
        cmap_table = check.getBestCmap()
        assert cmap_table is not None and len(cmap_table) >= len(normalized), f"Invalid cmap in {p}"
        check.close()

    print(f"Built {ttf_path.name} and {woff_path.name} ({len(normalized)} glyphs)")


def emit_ts_glyphs() -> None:
    def serialize(raw: Dict[str, GlyphDef]) -> Dict[str, dict]:
        out = {}
        for ch, (y_off, rows) in raw.items():
            w, yo, padded = normalize_glyph(y_off, rows)
            out[ch] = {"width": w, "yOffset": yo, "rows": padded}
        return out

    gothic_json = json.dumps(serialize(GOTHIC_RAW), ensure_ascii=True, indent=2)
    pixel_json = json.dumps(serialize(PIXEL_RAW), ensure_ascii=True, indent=2)

    content = f"""// Auto-generated by scripts/build_fonts.py — single source of truth with public/fonts/*.ttf
export interface BitmapGlyph {{
  width: number;
  yOffset: number;
  rows: readonly string[];
}}

export const MASOUL_GOTHIC_CAP_HEIGHT = 9;
export const MASOUL_PIXEL_CAP_HEIGHT = 7;

export const MASOUL_GOTHIC_GLYPHS: Record<string, BitmapGlyph> = {gothic_json};

export const MASOUL_PIXEL_GLYPHS: Record<string, BitmapGlyph> = {pixel_json};
"""
    OUT_TS.write_text(content, encoding="utf-8")
    print(f"Generated {OUT_TS}")


def main() -> None:
    build_font("MasoulGothic", GOTHIC_RAW, cap_height=9, x_height=6, space_px=4)
    build_font("MasoulPixel", PIXEL_RAW, cap_height=7, x_height=5, space_px=3)
    emit_ts_glyphs()


if __name__ == "__main__":
    main()
